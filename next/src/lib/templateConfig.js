// Cache resolved components to avoid repeated lookups
const componentCache = new Map();
const modalCache = new Map();

export function getCurrentTemplateName() {
  return getTemplateName();
}

export function resolveComponent(slot) {
  // Use cache to avoid repeated lookups
  if (componentCache.has(slot)) {
    return componentCache.get(slot);
  }

  const config =
    TEMPLATE_MAP[getTemplateName()] || TEMPLATE_MAP[DEFAULT_TEMPLATE];
  const component = config[slot];

  // Cache the result
  componentCache.set(slot, component);
  return component;
}

export function resolveModalComponent(modalKey) {
  // Use cache to avoid repeated lookups
  if (modalCache.has(modalKey)) {
    return modalCache.get(modalKey);
  }

  const config =
    TEMPLATE_MAP[getTemplateName()] || TEMPLATE_MAP[DEFAULT_TEMPLATE];
  const modal = config.modals?.[modalKey] || null;

  // Cache the result
  modalCache.set(modalKey, modal);
  return modal;
}

// Client-side template configuration - simplified and cached
let templateConfigCache = null;
export function getTemplateConfig() {
  if (templateConfigCache) {
    return templateConfigCache;
  }

  // Simplified config - theme is consistent across templates
  templateConfigCache = {
    theme: 'dark',
    template: getTemplateName(),
  };

  return templateConfigCache;
}
