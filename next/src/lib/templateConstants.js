// Helper function to get template config
export function getTemplateConfig(templateName = null) {
  const template =
    templateName || process.env.NEXT_PUBLIC_TEMPLATE || DEFAULT_TEMPLATE;
  return {
    ...COMMON_CONFIG,
    ...TEMPLATE_CONFIGS[template],
    template,
  };
}

// Helper function to validate template name
export function isValidTemplate(templateName) {
  return Object.values(TEMPLATE_NAMES).includes(templateName);
}
